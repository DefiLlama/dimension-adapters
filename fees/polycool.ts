/**
 * Polycool — copy-trading app for Polymarket (Telegram mini-app, iOS, Android).
 * https://polycoolapp.com · https://x.com/PolycoolApp · stats: https://polycoolapp.com/data
 *
 * Users trade Polymarket markets (manually or by copying leaders) from their own
 * wallet. Polycool charges a service fee on every buy and sell, 1.00% of the
 * notional for a new user, decreasing with lifetime volume down to 0.50%
 * ($100K+). The fee is pulled from the user's wallet at trade settlement as a
 * stablecoin transfer to the Polycool treasury on Polygon:
 *   - USDC.e until Polymarket's pUSD migration (first fee 2026-02-02),
 *   - pUSD (Polymarket's 1:1 USDC.e wrapper) since.
 *
 * Referrers earn 25% of the fees generated by the users they referred. The
 * reward accrues off-chain per trade and is paid on claim, as a pUSD transfer
 * from a dedicated payout wallet to the referrer (since 2026-07-01; before that
 * the ~$270 of claims were paid straight from the treasury and are not tracked).
 *
 * Income statement:
 *   dailyFees              — service fees received by the treasury (gross)
 *   dailyUserFees          — same: every fee is paid by the trader at fill time
 *   dailySupplySideRevenue — referral rewards paid out to referrers
 *   dailyRevenue           — fees minus referral payouts
 *   dailyProtocolRevenue   — same: no liquidity providers
 */

// Polycool fee treasury on Polygon. Receives only the per-trade service fees.
const TREASURY = "0x5cd4d6c28efc65028afa307712976f97ea87615c";

// Referral payout wallet: pays in-app referral claims in pUSD. (It also pays
// Polycool's KOL programme in USDC.e, which is marketing spend, not a fee
// share, so only pUSD transfers out of it are counted.)
const REFERRAL_PAYOUT_WALLET = "0x7537611f943272f53dbecabf5dcdd6a55ba7286e";

const PUSD_POLYGON = ADDRESSES.polygon.PUSD;
const USDC_E_POLYGON = ADDRESSES.polygon.USDC;

const SERVICE_FEES = "Service fees";
const SERVICE_FEES_TO_REFERRERS = "Service fees to referrers";
const SERVICE_FEES_TO_TREASURY = "Service fees to treasury";

const TRANSFER_ABI = "event Transfer(address indexed from, address indexed to, uint256 value)";

const fetch = async (options: FetchOptions): Promise<FetchResultV2> => {
  const dailyFees = options.createBalances();
  const dailySupplySideRevenue = options.createBalances();

  const fees = await addTokensReceived({
    options,
    targets: [TREASURY],
    tokens: [PUSD_POLYGON, USDC_E_POLYGON],
  });
  dailyFees.add(fees, SERVICE_FEES);

  // pUSD leaving the payout wallet = referral claims paid to referrers
  const payouts = await options.getLogs({
    target: PUSD_POLYGON,
    eventAbi: TRANSFER_ABI,
    topics: [
      "0xddf252ad1be2c89b69c2b068fc378daa952ba7f163c4a11628f55a4df523b3ef",
      "0x000000000000000000000000" + REFERRAL_PAYOUT_WALLET.slice(2),
    ],
  });
  for (const log of payouts) {
    if (String(log.to).toLowerCase() === TREASURY) continue; // internal move, not a reward
    dailySupplySideRevenue.add(PUSD_POLYGON, log.value, SERVICE_FEES_TO_REFERRERS);
  }

  const dailyRevenue = options.createBalances();
  dailyRevenue.add(fees, SERVICE_FEES_TO_TREASURY);
  dailyRevenue.subtract(dailySupplySideRevenue, SERVICE_FEES_TO_TREASURY);

  return {
    dailyFees,
    dailyUserFees: dailyFees.clone(),
    dailySupplySideRevenue,
    dailyRevenue,
    dailyProtocolRevenue: dailyRevenue.clone(),
  };
};

