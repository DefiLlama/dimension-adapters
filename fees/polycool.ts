import ADDRESSES from "../helpers/coreAssets.json";
import { FetchOptions, FetchResultV2, SimpleAdapter } from "../adapters/types";
import { CHAIN } from "../helpers/chains";
import { addTokensReceived } from "../helpers/token";
import { fetchPolymarketV2BuilderFees } from "../helpers/polymarket";

/**
 * Polycool — copy-trading app for Polymarket (Telegram mini-app, iOS, Android).
 * https://polycoolapp.com · https://x.com/PolycoolApp · stats: https://polycoolapp.com/data
 *
 * Users trade Polymarket markets (manually or by copying leaders) from their own
 * wallet. Two revenue streams:
 *
 *  1. Service fees. Polycool charges a fee on every buy and sell, 1.00% of the
 *     notional for a new user, decreasing with lifetime volume down to 0.50%
 *     ($100K+). Pulled from the user's wallet at trade settlement as a
 *     stablecoin transfer to the Polycool treasury on Polygon: USDC.e until
 *     Polymarket's pUSD migration (first fee 2026-02-02), pUSD since.
 *
 *  2. Polymarket builder fees. Polycool is a Polymarket v2 builder; every
 *     attributed trade carries a builder fee that Polymarket pays out to the
 *     builder wallet (pUSD, daily). Read from the CLOB builder-trades API by
 *     builder code, like the other Polymarket builders in this repo.
 *
 * Referrers earn 25% of the service fees generated by the users they referred.
 * The reward accrues off-chain per trade and is paid on claim, as a pUSD
 * transfer from a dedicated payout wallet (since 2026-07-01; the ~$270 of
 * earlier claims were paid straight from the treasury and are not tracked).
 *
 * Income statement:
 *   dailyFees              — service fees + builder fees
 *   dailyUserFees          — service fees (paid by the trader at fill time)
 *   dailySupplySideRevenue — referral rewards paid out to referrers
 *   dailyRevenue           — fees minus referral payouts
 *   dailyProtocolRevenue   — same: no liquidity providers
 */

// Polycool fee treasury on Polygon. Receives only the per-trade service fees.
const TREASURY = "0x5cd4d6c28efc65028afa307712976f97ea87615c";

// Referral payout wallet: pays in-app referral claims in pUSD. (It also pays
// Polycool's KOL programme in USDC.e, which is marketing spend, not a fee
// share, so only pUSD transfers out of it are counted.)
const REFERRAL_PAYOUT_WALLET = "0x7537611f943272f53dbecabf5dcdd6a55ba7286e";

// Polycool's Polymarket v2 builder code (attached to every CLOB order).
const POLYMARKET_BUILDER_CODE = "0x9700262d1ce6bbfde7247f0f849a0814f7faa7496674a221622e06fdb25b0f61";
const POLYMARKET_BUILDER_START = 1777420800; // 2026-04-29, Polymarket v2 builder fees go live

const PUSD_POLYGON = ADDRESSES.polygon.PUSD;
const USDC_E_POLYGON = ADDRESSES.polygon.USDC;

const SERVICE_FEES = "Service fees";
const BUILDER_FEES = "Polymarket builder fees";
const REFERRAL_REWARDS = "Referral rewards";

const TRANSFER_ABI = "event Transfer(address indexed from, address indexed to, uint256 value)";

const fetch = async (options: FetchOptions): Promise<FetchResultV2> => {
  const dailyFees = options.createBalances();
  const dailyUserFees = options.createBalances();
  const dailySupplySideRevenue = options.createBalances();

  const serviceFees = await addTokensReceived({
    options,
    targets: [TREASURY],
    tokens: [PUSD_POLYGON, USDC_E_POLYGON],
  });
  dailyFees.add(serviceFees, SERVICE_FEES);
  dailyUserFees.add(serviceFees, SERVICE_FEES);

  if (options.endTimestamp > POLYMARKET_BUILDER_START) {
    const builder = await fetchPolymarketV2BuilderFees({ options, builderCode: POLYMARKET_BUILDER_CODE });
    dailyFees.add(builder.dailyFees, BUILDER_FEES);
  }

  // pUSD leaving the payout wallet = referral claims paid to referrers
  const payouts = await options.getLogs({
    target: PUSD_POLYGON,
    eventAbi: TRANSFER_ABI,
    topics: [
      "0xddf252ad1be2c89b69c2b068fc378daa952ba7f163c4a11628f55a4df523b3ef",
      "0x000000000000000000000000" + REFERRAL_PAYOUT_WALLET.slice(2),
    ],
  });
  for (const log of payouts) {
    if (String(log.to).toLowerCase() === TREASURY) continue; // internal move, not a reward
    dailySupplySideRevenue.add(PUSD_POLYGON, log.value, REFERRAL_REWARDS);
  }

  const dailyRevenue = dailyFees.clone();
  dailyRevenue.subtract(dailySupplySideRevenue, SERVICE_FEES);

  return {
    dailyFees,
    dailyUserFees,
    dailySupplySideRevenue,
    dailyRevenue,
    dailyProtocolRevenue: dailyRevenue,
  };
};

const adapter: SimpleAdapter = {
  version: 2,
  allowNegativeValue: true, // a referral claim can exceed the fees of a quiet day
  methodology: {
    Fees: "Service fees charged by Polycool on every Polymarket buy and sell routed through the app (1.00% of the notional for new users, decreasing with lifetime volume to 0.50% above $100K, pulled from the trader's wallet at settlement into the Polycool treasury as USDC.e or pUSD), plus the Polymarket builder fees earned on those trades as a Polymarket v2 builder.",
    UserFees: "Service fees only, paid by the trader at fill time. Builder fees are paid by Polymarket.",
    SupplySideRevenue: "Referral rewards: referrers earn 25% of the service fees generated by the users they referred. Counted when paid, as pUSD transfers from the referral payout wallet to referrers (claims before 2026-07-01, about $270 in total, were paid from the treasury and are not tracked).",
    Revenue: "Service fees plus builder fees, minus referral rewards paid out. No liquidity providers.",
    ProtocolRevenue: "Same as Revenue: everything that is not paid to referrers stays with Polycool.",
  },
  breakdownMethodology: {
    Fees: {
      [SERVICE_FEES]: "Incoming pUSD and USDC.e `Transfer` events to the Polycool treasury `0x5cd4d6c28efc65028afa307712976f97ea87615c` on Polygon, each one a service fee pulled from a trader's wallet at trade settlement.",
      [BUILDER_FEES]: "Builder fees of the trades attributed to Polycool's Polymarket builder code, from the CLOB builder-trades API (paid out by Polymarket to the builder wallet in pUSD).",
    },
    SupplySideRevenue: {
      [REFERRAL_REWARDS]: "Outgoing pUSD `Transfer` events from the referral payout wallet `0x7537611f943272f53dbecabf5dcdd6a55ba7286e` on Polygon, each one a referral claim paid to a referrer.",
    },
  },
  adapter: {
    [CHAIN.POLYGON]: {
      fetch,
      start: "2026-02-02",
    },
  },
};

export default adapter;
