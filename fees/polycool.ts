/**
 * Polycool — copy-trading app for Polymarket (Telegram mini-app, iOS, Android).
 * https://polycoolapp.com · https://x.com/PolycoolApp · stats: https://polycoolapp.com/data
 *
 * Users trade Polymarket markets (manually or by copying leaders) from their own
 * wallet. Two revenue streams, both paid by the trader:
 *
 *  1. Service fees. Polycool charges a fee on every buy and sell, 1.00% of the
 *     notional for a new user, decreasing with lifetime volume down to 0.50%
 *     ($100K+). Pulled from the user's wallet as a stablecoin transfer to the
 *     Polycool treasury on Polygon: USDC.e until Polymarket's pUSD migration
 *     (first fee 2026-02-02), pUSD since.
 *
 *  2. Polymarket builder fees. Polycool is a Polymarket v2 builder; every
 *     attributed trade carries a builder fee that the trader pays inside
 *     Polymarket's trade fee. Polymarket collects it at its v2 fee recipient and
 *     pays it out daily (pUSD) to Polycool's builder wallet. Read from the CLOB
 *     builder-trades API by builder code, like the other Polymarket builders in
 *     this repo.
 *
 * Referrers earn 25% of the service fees generated by the users they referred.
 * The reward accrues off-chain per trade and is paid on claim, as a pUSD
 * transfer from a dedicated payout wallet (since 2026-07-01; the ~$270 of
 * earlier claims were paid straight from the treasury and are not tracked).
 *
 * Wallet rotation: the keys of the original treasury and payout wallet were
 * compromised on 2026-10-21 (both drained that evening, ~$230 in total). From
 * 2026-10-22 service fees go to a new treasury, which also pays referral claims.
 *
 * Income statement:
 *   dailyFees              — service fees + builder fees
 *   dailyUserFees          — same: the trader pays both
 *   dailySupplySideRevenue — referral rewards paid out to referrers
 *   dailyRevenue           — fees minus referral payouts
 *   dailyProtocolRevenue   — same: no liquidity providers
 *
 * The builder fees are also inside Polymarket's own fees (fees/polymarket.ts counts
 * everything reaching its v2 fee recipient, builder share included), hence doublecounted.
 */

// Polycool fee treasuries on Polygon. They receive only the per-trade service fees.
const OLD_TREASURY = "0x5cd4d6c28efc65028afa307712976f97ea87615c"; // until 2026-10-21 (key compromised)
