const LABELS = {
  PLATFORM: 'Platform Fees',
  CREATOR: 'Creator Fees',
  REFERRER: 'Referrer Fees',
  RESOLVER: 'Resolver Fees',
} as const;

// Claim amounts are denominated in the pool's token: RAIN for most pools, USDT for the rest.
const PlatformFeeClaimEvent = "event PlatformClaim(address indexed wallet, uint256 amount)"; // burnt as fees
const CreatorFeeClaimEvent = "event CreatorClaim(address indexed wallet, uint256 amount)"; // paid to pool creators
const ReferrerFeeClaimEvent = "event RefererClaim(address indexed wallet, uint256 amount)"; // paid to referer
const ResolverFeeClaimEvent = "event ResolverClaim(address indexed wallet, uint256 amount)"; // paid to resolver
const ClaimEvent = "event Claim(address indexed wallet, uint256 winnerOption, uint256 amount, uint256 reward, uint256 totalReward)"; // claimed by users (also includes pool liquidity incentive rewards)
const poolTokenSetEvent =
  "event PoolTokenSet(address indexed poolAddress,address indexed tokenAddress,uint256 tokenDecimals,string tokenName,string tokenSymbol)";

const rainFactories: { address: string; fromBlock: number; toBlock?: number }[] = [
  // factory 0xccCB... was NOT retired; remove toBlock cap so it picks up pools after block 446061342
  { address: "0xccCB3C03D9355B01883779EF15C1Be09cf3623F1", fromBlock: 307026817 },
  // active factory
  { address: "0xA8640B62D755e42C9ed6A86d0fc65CE09e31F264", fromBlock: 446257605 },
];
const poolCreatedEvent =
  "event PoolCreated(address indexed poolAddress, address indexed poolCreator, string uri)";
const fetch = async (options: FetchOptions) => {
  const dailyFees = options.createBalances(); // overall fees of each pool from protocol
  const dailyRevenue = options.createBalances(); // revenue generated by the protocol from platformFees
  const dailySupplySideRevenue = options.createBalances(); // creator, referrer and resolver shares


  const poolCreationLogs: any[] = [];
  for (const factory of rainFactories) {
    const logs = await options.getLogs({
      target: factory.address,
      eventAbi: poolCreatedEvent,
      fromBlock: factory.fromBlock,
      toBlock: factory.toBlock,
      cacheInCloud: true,
    });
    poolCreationLogs.push(...logs);
  }

  const pools = poolCreationLogs.map((log) => log.poolAddress);

  const poolTokenSetLogs: any[] = [];
  for (const factory of rainFactories) {
    const logs = await options.getLogs({
      target: factory.address,
      eventAbi: poolTokenSetEvent,
      fromBlock: factory.fromBlock,
      toBlock: factory.toBlock,
      cacheInCloud: true,
    });
    poolTokenSetLogs.push(...logs);
  }

  const poolTokenMap: Record<string, { token: string; decimals: number }> = {
    // missing poolTokenSetEvent log for this pool
    '0xbfda181ba56da848172d0a73c9e13caa1abdea30': {
      token: ADDRESSES.arbitrum.USDT,
      decimals: 6,
    }
  };

  poolTokenSetLogs.forEach((log) => {
    poolTokenMap[log.poolAddress.toLowerCase()] = {
      token: log.tokenAddress.toLowerCase(),
      decimals: Number(log.tokenDecimals),
    };
  });

  const addLogFees = (label: string) => (logs: any[]) => {
    if (!logs || logs.length === 0) return;
    logs.forEach((log: any) => {
      const pool = log.address.toLowerCase();
      const tokenInfo = poolTokenMap[pool]
      if (!tokenInfo?.token) {
        console.warn(`Token info not found for pool ${pool}, skipping log with amount ${log.args.amount}`);
        return;
      }
      dailyFees.add(tokenInfo.token, log.args.amount, label);
      dailySupplySideRevenue.add(tokenInfo.token, log.args.amount, label);
    })
  }

  await processLogs({
    options, pools, eventAbi: PlatformFeeClaimEvent, processor: (logs: any) => {
      if (!logs || logs.length === 0) return;
      logs.forEach((log: any) => {
        const pool = log.address.toLowerCase();
        const tokenInfo = poolTokenMap[pool]
        if (!tokenInfo?.token) {
          console.warn(`Token info not found for pool ${pool}, skipping log with amount ${log.args.amount}`);
          return;
        }
        dailyFees.add(tokenInfo.token, log.args.amount, LABELS.PLATFORM);
        dailyRevenue.add(tokenInfo.token, log.args.amount, LABELS.PLATFORM); 
      })
    }
  })

  await processLogs({ options, pools, eventAbi: CreatorFeeClaimEvent, processor: addLogFees(LABELS.CREATOR) })
  await processLogs({ options, pools, eventAbi: ReferrerFeeClaimEvent, processor: addLogFees(LABELS.REFERRER) })
  await processLogs({ options, pools, eventAbi: ResolverFeeClaimEvent, processor: addLogFees(LABELS.RESOLVER) })
  // await processLogs({ options, pools, eventAbi: ClaimEvent, processor: addLogFees })

  return {
    dailyFees,
    dailyUserFees: dailyFees,
    dailyRevenue,
    dailyHoldersRevenue: dailyRevenue,
    dailySupplySideRevenue,
  };


  async function processLogs({ eventAbi, processor }: { options: FetchOptions, pools: string[], eventAbi: string, processor: (logs: any[]) => void }) {

    return options.streamLogs({
      noTarget: true,
      eventAbi,
      entireLog: true,
      targetsFilter: pools,
      processor,
    })
  }

};

