const adapter: SimpleAdapter = {
  version: 2,
  pullHourly: true,
  fetch,
  adapter: CHAIN_CONFIG,
  methodology,
  breakdownMethodology,
  // Strategies realise losses (write-downs, exits below the marked rate); those are real negative yield.
  allowNegativeValue: true,
};

export default adapter;
