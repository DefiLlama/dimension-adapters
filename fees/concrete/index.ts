import { FetchOptions, SimpleAdapter } from "../../adapters/types";
import { METRIC } from "../../helpers/metrics";
import { integrate } from "./accounting";
import { CHAIN_CONFIG, STAKING_REWARDS_CAMPAIGNS } from "./config";
import { readRatePoints, supplyEvents, trackedVaults } from "./onchain";

// Concrete vaults are ERC-4626 multi-strategy vaults. Depositor yield is the growth of each
// vault's exchange rate, measured on-chain between every share mint and burn (see accounting.ts);
// protocol revenue is the shares minted to the fee recipients; partner staking rewards campaigns
// are booked on their distribution day.

const fetch = async (options: FetchOptions) => {
  const dailyFees = options.createBalances();
  const dailyRevenue = options.createBalances();
  const dailySupplySideRevenue = options.createBalances();

  const vaults = await trackedVaults(options);
  const events = await supplyEvents(options, vaults);
  const points = await readRatePoints(options, vaults, events);

  for (const vault of vaults) {
    const { holderYield, managementFees, performanceFees } = integrate(points.get(vault.address)!, events.get(vault.address)!.feeMints, vault);
    // `base` keys carry their own chain: converted underlying assets are priced through a mainnet token.
    const add = (balances: typeof dailyFees, amount: bigint, label: string) =>
      balances.add(vault.base, amount.toString(), { label, skipChain: true });
    add(dailyFees, holderYield, METRIC.ASSETS_YIELDS);
    add(dailySupplySideRevenue, holderYield, METRIC.ASSETS_YIELDS);
    add(dailyFees, managementFees, METRIC.MANAGEMENT_FEES);
    add(dailyRevenue, managementFees, METRIC.MANAGEMENT_FEES);
    add(dailyFees, performanceFees, METRIC.PERFORMANCE_FEES);
    add(dailyRevenue, performanceFees, METRIC.PERFORMANCE_FEES);
  }

  await addStakingRewardsCampaigns(options, [dailyFees, dailySupplySideRevenue]);

  return { dailyFees, dailyRevenue, dailySupplySideRevenue, dailyProtocolRevenue: dailyRevenue };
};

/** Campaigns whose distribution day falls in the window, in their token's units. */
async function addStakingRewardsCampaigns(options: FetchOptions, balances: ReturnType<FetchOptions['createBalances']>[]) {
  for (const campaign of STAKING_REWARDS_CAMPAIGNS) {
    if (campaign.chain !== options.chain) continue;
    const distributedAt = Math.floor(new Date(`${campaign.distributedOn}T00:00:00Z`).getTime() / 1e3);
    if (distributedAt <= options.fromTimestamp || distributedAt > options.toTimestamp) continue;
    const decimals = Number(await options.api.call({ abi: 'uint8:decimals', target: campaign.token }));
    for (const balance of balances) balance.add(campaign.token, toRawUnits(campaign.amount, decimals), METRIC.STAKING_REWARDS);
  }
}

function toRawUnits(amount: string, decimals: number): string {
  const [whole, fraction = ''] = amount.split('.');
  return BigInt(whole + fraction.padEnd(decimals, '0').slice(0, decimals)).toString();
}

