import fetchURL from "../../utils/fetchURL";
import { FetchOptions, SimpleAdapter, FetchResult } from "../../adapters/types";
import { CHAIN } from "../../helpers/chains";

const histogramUrl = (typ: 'vol' | 'fee', pool?: string) =>
  `https://app.magmafinance.io/api/sui/histogram?date_type=day&typ=${typ}&limit=40${pool ? `&address=${pool}` : ''}`

// wash trading, sample tx https://suivision.xyz/txblock/DY3oSw6KHjwuVtQCYvG1S4YoqNZwRtnWcfwWdX77L1T1
const blPools = [
  '0xe31dbd5637fc3a104a5bcad2a28d7942198271ed4503d4949f81467494fd582e',
  '0xfbc6374ae9533fc9f24a4ca705edfb58021cab24870c024bd6d0caec1c64cf36',
  '0xfa54f1de53af9135aea64d31e8e4b543fc0b073a6c218f520f5b015d28951a0a',
]

const series: { [key: string]: Promise<any[]> } = {}

function daySeries(typ: 'vol' | 'fee', pool?: string): Promise<any[]> {
  const key = `${typ}|${pool ?? ''}`
  if (!series[key]) series[key] = fetchURL(histogramUrl(typ, pool))
    .then(({ data }: any) => data.list)
    .catch((e: any) => { delete series[key]; throw e })
  return series[key]
}

async function dayValue(typ: 'vol' | 'fee', date: string, pool?: string): Promise<number> {
  const list = await daySeries(typ, pool)
  const day = list.find((item: any) => item.date.slice(0, 10) === date)
  if (!day) throw new Error(`magma ${typ} histogram${pool ? ` for pool ${pool}` : ''} has no entry for ${date}`)
  return Number(day.num)
}

async function excludingBlPools(typ: 'vol' | 'fee', date: string): Promise<number> {
  const [total, ...excluded] = await Promise.all([undefined, ...blPools].map((pool) => dayValue(typ, date, pool)))
  return excluded.reduce((rest, value) => rest - value, total)
}

const fetch = async (options: FetchOptions): Promise<FetchResult> => {
  const date = new Date(options.startOfDay * 1000).toISOString().slice(0, 10)
  const [dailyVolume, dailyFees] = await Promise.all([excludingBlPools('vol', date), excludingBlPools('fee', date)])

  return {
    dailyVolume,
    dailyFees,
    dailyRevenue: dailyFees * 0.2,
    dailyProtocolRevenue: dailyFees * 0.2,
  };
};

const adapter: SimpleAdapter = {
  version: 1,
  fetch,
  chains: [CHAIN.SUI],
  start: "2025-02-12",
  methodology: {
    Fees: "Swap fees generated by the swap transactions on Magma Finance.",
    Revenue: "Protocol fees charged from the swap fees.",
    ProtocolRevenue: "Protocol fees charged from the swap fees.",
  },
};

export default adapter;
